assert keep.read_text() == 'preserve'
assert json.loads(progress.read_text())['phase'] == 'complete'
assert (instance / 'data/webui.json').stat().st_mode & 0o777 == 0o600
run('install.sh', args + ['--resume'])
assert (instance / 'data/webui.json').stat().st_mode & 0o777 == 0o600
